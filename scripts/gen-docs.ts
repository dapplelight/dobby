const read = (n: string) => readFileSync(`${MANUAL}${n}.md`, "utf8")
/** Writes the generated pages and the llms files under `docs` (default: this repo's docs/). The manual's other pages are read from the repo. */
export function write(docs = fileURLToPath(new URL("../docs/", import.meta.url))) {
  const put = (f: string, s: string) => (mkdirSync(dirname(`${docs}${f}`), { recursive: true }), writeFileSync(`${docs}${f}`, s))
  const gen: Record<string, string> = { config: configMd(), cli: cliMd(), stats: statsMd(), glossary: glossaryMd(), "safety-categories": safetyMd() }
  for (const [n, s] of Object.entries(gen)) put(`manual/${n}.md`, s)
  const ps = pages(), body = (n: string) => gen[n] ?? read(n)
  const sections = GROUPS.flatMap((g) => ["", `## ${g}`, "", ...ps.filter((p) => p.group === g).map((p) => `- [${p.title}](manual/${p.name}.md): ${p.summary}`)])
  put("llms.txt", ["# Dobby", "", "> Dobby runs Claude Code on your tickets and opens reviewed pull requests. It is in public beta.", ...sections].join("\n") + "\n")
  put("llms-full.txt", ps.map((p) => `<!-- manual/${p.name}.md -->\n${render(body(p.name), p.name)}\n`).join("\n"))
}

if (process.argv[1] === fileURLToPath(import.meta.url)) write()
